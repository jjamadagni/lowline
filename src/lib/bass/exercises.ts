const note = (string: number, fret: number, beats = 1): Step => ({
  rest: false,
  string,
  fret,
  beats,
});
const rest = (beats = 1): Step => ({ rest: true, beats });

const gallop = (string: number, fret: number): Step[] => [
  note(string, fret, 0.5),
  note(string, fret, 0.25),
  note(string, fret, 0.25),
];

