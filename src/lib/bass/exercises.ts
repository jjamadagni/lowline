export function openExercises(completed: readonly string[]) {
  return EXERCISES.filter((exercise) => completed.includes(exercise.needs));
}

export function nextLockedExercise(completed: readonly string[]) {
  return EXERCISES.find((exercise) => !completed.includes(exercise.needs)) ?? null;
}
